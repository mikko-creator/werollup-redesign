// render-changelog.mjs - docs/CHANGE-LOG.md from src/content/changes.json (the pipeline's machine ledger of every
// deliberate difference from the source). Orchestrator-owned. Deterministic; re-run after every extract.
//   node tools/render-changelog.mjs [--check]   (--check: exit 1 if docs/CHANGE-LOG.md is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const led = JSON.parse(fs.readFileSync(path.join(ROOT, 'src', 'content', 'changes.json'), 'utf8'));
const items = led.changes;
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const RULES = {
  A7: 'Mechanical defects that are not wording (OPEN-DECISIONS A7)',
  A8: 'Broken link targets corrected where the right target is proven on the site (A8)',
  A12: 'Contact form: posts, submit disabled until a backend is configured (A12)',
  A15: 'Tracking and the agency credit stripped (A15)',
  A16: 'Exactly one h1 per page (A16)',
};
// group identical changes (same rule, id, before, after) across pages
const groups = new Map();
for (const c of items) {
  const k = [c.rule, c.id, c.region, c.before, c.after].join('\u0000');
  if (!groups.has(k)) groups.set(k, { ...c, pages: [], total: 0 });
  const g = groups.get(k);
  g.pages.push(c.page);
  g.total += c.count || 1;
}
const out = [];
out.push('# Change log: deliberate differences from the live site');
out.push('');
out.push('Generated by `node tools/render-changelog.mjs` from `src/content/changes.json`, the pipeline ledger. Do not edit');
out.push('this file by hand: edit the rule, re-extract, and re-render. Everything not listed here is carried verbatim, and');
out.push('`tools/text-parity.mjs` and `tools/build-check.mjs` prove that on the built pages.');
out.push('');
out.push('Ledger: ' + items.length + ' entries in ' + groups.size + ' distinct changes. Counts by rule: ' +
  Object.entries(items.reduce((m, c) => ((m[c.rule] = (m[c.rule] || 0) + 1), m), {})).sort().map(([r, n]) => r + ' ' + n).join(', ') + '.');
for (const rule of Object.keys(RULES)) {
  const gs = [...groups.values()].filter((g) => g.rule === rule);
  if (!gs.length) continue;
  out.push('');
  out.push('## ' + rule + ': ' + RULES[rule]);
  out.push('');
  out.push('| id | pages | region | before | after | why | evidence |');
  out.push('|---|---|---|---|---|---|---|');
  for (const g of gs) {
    const pages = g.pages.length > 3 ? g.pages.length + ' pages (e.g. ' + g.pages.slice(0, 2).join(', ') + ')' : g.pages.join(', ');
    out.push('| ' + [g.id, pages + (g.total !== g.pages.length ? '; ' + g.total + ' occurrences' : ''), g.region, '`' + esc(g.before) + '`', '`' + esc(g.after) + '`', esc(g.why), esc(g.evidence)].join(' | ') + ' |');
  }
}
const unknown = items.filter((c) => !RULES[c.rule]);
if (unknown.length) { console.error('unknown rule(s) in the ledger: ' + [...new Set(unknown.map((c) => c.rule))].join(', ')); process.exitCode = 1; }
const text = out.join('\n') + '\n';
const target = path.join(ROOT, 'docs', 'CHANGE-LOG.md');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== text) { console.error('docs/CHANGE-LOG.md is out of date: run node tools/render-changelog.mjs'); process.exitCode = 1; }
  else console.log('CHANGE-LOG.md up to date (' + items.length + ' entries, ' + groups.size + ' distinct)');
} else {
  fs.writeFileSync(target, text);
  console.log('wrote docs/CHANGE-LOG.md: ' + items.length + ' entries in ' + groups.size + ' distinct changes');
}
